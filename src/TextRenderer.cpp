void drawChar(float x, float y, char c, float s)
{
    if (c < 32 || c > 127) return;

    const unsigned char* glyph = font[c - 32];

    glBegin(GL_QUADS);

    for (int row = 0; row < 8; row++) {
        for (int col = 0; col < 8; col++) {

            if (glyph[row] & (1 << (7 - col))) {

                float px = x + col * s;
                float py = y - row * s;   // ✅ FIX

                glVertex2f(px, py);
                glVertex2f(px + s, py);
                glVertex2f(px + s, py - s);
                glVertex2f(px, py - s);
            }
        }
    }

    glEnd();
}




void drawText(float x, float y,
              const std::string& text,
              float scale)
{
    float startX = x;

    for (char c : text) {
        drawChar(startX, y, c, scale);
        startX += 9 * scale;
    }
}
